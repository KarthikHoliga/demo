const square = (n) => n * n;
const cube = (n) => n * n * n;
const pi = () => 3.14159;
const add = (a, b) => a + b;
const hello = () => "Hello World";

console.log(square(5)); // Output: 25
console.log(cube(3)); // Output: 27
console.log(pi()); // Output: 3.14159
console.log(add(3, 4)); // Output: 7
console.log(hello()); // Output: Hello World